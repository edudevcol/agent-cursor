// Regenerates src/overlay/avatar-images.ts from the PNGs in assets/avatars/.
// Run with: npm run embed-avatars  (after replacing or adding an avatar PNG)
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = ["businessperson", "robot", "tester", "detective", "ninja", "ghost", "cat", "alien"];

const entries = NAMES.map((name) => {
  const base64 = readFileSync(`assets/avatars/${name}.png`).toString("base64");
  return `  ${name}: "data:image/png;base64,${base64}",`;
});

const source = `// AUTO-GENERATED by scripts/embed-avatars.mjs from assets/avatars/*.png. Do not edit by hand.
import type { BuiltinAvatarName } from "../options.js";

export const AVATAR_IMAGES: Record<BuiltinAvatarName, string> = {
${entries.join("\n")}
};
`;

writeFileSync("src/overlay/avatar-images.ts", source);
console.log(`src/overlay/avatar-images.ts written (${(source.length / 1024).toFixed(1)} KB)`);
